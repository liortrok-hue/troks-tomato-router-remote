package com.troks.tomatorouters.ui

import androidx.compose.runtime.staticCompositionLocalOf
import androidx.compose.ui.unit.LayoutDirection
import java.util.Locale

enum class AppLanguage(val code: String, val label: String, val direction: LayoutDirection, val strings: Strings) {
    HEBREW("he", "עברית", LayoutDirection.Rtl, Hebrew),
    ENGLISH("en", "English", LayoutDirection.Ltr, English),
    RUSSIAN("ru", "Русский", LayoutDirection.Ltr, Russian),
    ARABIC("ar", "العربية", LayoutDirection.Rtl, Arabic);

    companion object {
        fun fromCode(code: String?): AppLanguage = entries.firstOrNull { it.code == code } ?: systemDefault()

        fun systemDefault(): AppLanguage = when (Locale.getDefault().language) {
            "he", "iw" -> HEBREW
            "ru" -> RUSSIAN
            "ar" -> ARABIC
            else -> ENGLISH
        }
    }
}

